namespace BasicToAdvancedLearning.EfCoreBasics;

// The two entity classes of Topic 14. An "entity" is an ordinary C# class that EF Core maps to a table:
// one object = one row, one property = one column. They are plain classes - no base class, no attributes
// and no EF Core code in them. They map the same two tables (Customers and Accounts) as the
// SQL topics, with the same columns and sizes. Defaults and CHECK rules from the hand-written SQL are not part of this model
// (EF Core can express them with HasDefaultValueSql and HasCheckConstraint, but that is not covered here).
public class Customer
{
    // Convention: a property called Id, or <ClassName>Id like this one, becomes the primary key.
    // An int key is generated by the database (IDENTITY), so it is 0 until the row has been saved.
    public int CustomerId { get; set; }

    // With nullable reference types switched on (this project does), a plain `string` means "never null",
    // so EF Core makes the column NOT NULL. A `string?` would make it NULL-able.
    public string FullName { get; set; } = "";

    public string Email { get; set; } = "";

    public DateTime CreatedAt { get; set; }

    // Navigation property (the "one" side): all accounts of this customer, found by following the
    // object reference instead of writing a JOIN. It is not a column; the foreign key lives on Account.
    public List<Account> Accounts { get; set; } = new();
}

public class Account
{
    public int AccountId { get; set; }

    // Convention: a property named after the navigation property plus "Id" (the navigation below is
    // Customer, so CustomerId) is recognised as the foreign key column that points at Customers.
    // Because it is a plain int (not int?), every account must have a customer.
    public int CustomerId { get; set; }

    public string AccountNumber { get; set; } = "";

    public string AccountType { get; set; } = "";

    public decimal Balance { get; set; }

    // Navigation property (the "many" side): the customer who owns this account. It can be null
    // while the object is being built, which is why the type is `Customer?`.
    public Customer? Customer { get; set; }
}
