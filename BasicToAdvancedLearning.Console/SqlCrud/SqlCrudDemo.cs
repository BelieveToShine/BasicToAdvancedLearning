using BasicToAdvancedLearning.Interfaces;

namespace BasicToAdvancedLearning.SqlCrud;

// Topic 12: SQL CRUD — Create (INSERT), Read (SELECT), Update, Delete — plus transactions, the tool that
// makes several changes succeed or fail TOGETHER. SELECT is Topic 11's subject, so here it is only used to
// look at the rows; the new ideas are INSERT, UPDATE, DELETE and BEGIN TRANSACTION / COMMIT / ROLLBACK.
// The running example is the bank: Customers, Accounts and a Transactions ledger (each row is one deposit
// or withdrawal). SqlCrudSetup.cs drops and recreates those three tables, empty; each method below then
// builds on the rows the one before it left behind.
// How C# really talks to SQL Server (SqlConnection, SqlCommand, parameters) is Topic 13. Here the SQL text
// goes through SqlLab.Run (a statement that returns no rows; its result is the number of rows changed) and
// SqlLab.Show (a SELECT, printed as a grid) — each call is its own batch on its own connection.
// See ArchitectureDiagrams/SqlCrud for the visual walkthrough.
public class SqlCrudDemo
{
    // INSERT adds new rows. Name the columns you fill, then give one list of values per row.
    public void ExplainInsertRows()
    {
        PrintHeading("1. INSERT — adding rows");

        // One row. The "column list" (FullName, Email) says which columns the values belong to. We leave
        // out CustomerId (IDENTITY: SQL Server numbers the row itself, you normally never supply it) and
        // CreatedAt (it has a DEFAULT, which SQL Server uses when you leave that column out).
        // The N before a quote marks Unicode text, which is what NVARCHAR columns hold.
        int oneRow = SqlLab.Run("""
            INSERT INTO Customers (FullName, Email)
            VALUES (N'Asha Rao', N'asha@example.com');
            """);
        Console.WriteLine($"INSERT one row: {oneRow} row affected");

        // Several rows in ONE statement: one (...) list per row, separated by commas. It is one statement,
        // so it succeeds or fails as a whole.
        int twoRows = SqlLab.Run("""
            INSERT INTO Customers (FullName, Email)
            VALUES (N'Ben Carter', N'ben@example.com'),
                   (N'Chen Li',    N'chen@example.com');
            """);
        Console.WriteLine($"INSERT two rows in one statement: {twoRows} rows affected");
        SqlLab.Show("""
            SELECT CustomerId, FullName, Email,
                   CASE WHEN CreatedAt IS NULL THEN 'missing' ELSE 'filled by DEFAULT' END AS CreatedAt
            FROM Customers ORDER BY CustomerId;
            """);

        // WHY you often need the new row's number: a child row (a deposit) must point at it. SCOPE_IDENTITY()
        // returns the last IDENTITY number generated on this connection, in this scope (batch). It belongs to one connection, and every
        // SqlLab call is a fresh connection, so we ask for it in the SAME batch as the INSERT.
        // (Asha's CustomerId is 1, as the grid above shows.)
        Console.WriteLine("Open Asha's account, then use its new AccountId for the first deposit:");
        SqlLab.Show("""
            INSERT INTO Accounts (CustomerId, AccountNumber, AccountType, Balance)
            VALUES (1, N'SAV-1001', N'Savings', 500);
            DECLARE @NewAccountId INT = SCOPE_IDENTITY();
            INSERT INTO Transactions (AccountId, Amount, Kind)
            VALUES (@NewAccountId, 500, N'Deposit');
            SELECT @NewAccountId AS NewAccountId;
            """);

        // The other way: OUTPUT hands back columns of the rows that were really inserted. It works for many
        // rows at once (SCOPE_IDENTITY holds just ONE number) and shows what was stored, including values
        // filled by DEFAULT: the keyword DEFAULT in the value list asks for the column's default (0 here).
        // Avoid @@IDENTITY: it also sees numbers generated by a trigger's own INSERT, so it can hand back a
        // number that is not the row you just added. SCOPE_IDENTITY ignores those.
        Console.WriteLine("Two more accounts, with OUTPUT showing what was stored:");
        SqlLab.Show("""
            INSERT INTO Accounts (CustomerId, AccountNumber, AccountType, Balance)
            OUTPUT INSERTED.AccountId, INSERTED.AccountNumber, INSERTED.Balance
            VALUES (2, N'CUR-2001', N'Current', DEFAULT),
                   (3, N'SAV-3001', N'Savings', DEFAULT);
            """);
    }

    // UPDATE changes rows that already exist. WHERE chooses which ones — leave it out and EVERY row changes.
    public void ExplainUpdateRows()
    {
        PrintHeading("2. UPDATE — changing rows, and why WHERE matters");

        // SET says what to change; WHERE says which rows. Filtering on the primary key (CustomerId)
        // targets exactly one row, because no two rows share a key value.
        int emailsChanged = SqlLab.Run("UPDATE Customers SET Email = N'asha.rao@example.com' WHERE CustomerId = 1;");
        Console.WriteLine($"UPDATE ... WHERE CustomerId = 1: {emailsChanged} row affected");
        SqlLab.Show("SELECT CustomerId, FullName, Email FROM Customers WHERE CustomerId = 1;");

        // A WHERE that matches nothing is NOT an error: the UPDATE succeeds and changes 0 rows. Inside SQL,
        // @@ROWCOUNT holds the number of rows the previous statement affected (any later statement resets
        // it); SqlLab.Run gave us the same number as its return value above.
        Console.WriteLine("A WHERE that matches no row (CustomerId 999):");
        SqlLab.Show("UPDATE Customers SET Email = N'nobody@example.com' WHERE CustomerId = 999; SELECT @@ROWCOUNT AS RowsAffected;");

        // Now the classic mistake — on a throwaway COPY of the accounts, never on the real table.
        // SELECT ... INTO creates a new table holding the query's rows.
        // The plan: charge Asha a 25.00 fee. SET Balance = Balance - 25 reads the OLD balance and writes the new one.
        SqlLab.Run("SELECT AccountId, AccountNumber, Balance INTO AccountsScratch FROM Accounts;");
        Console.WriteLine("The scratch copy before the mistake:");
        SqlLab.Show("SELECT AccountId, AccountNumber, Balance FROM AccountsScratch ORDER BY AccountId;");

        // Oops: the WHERE (... WHERE AccountNumber = N'SAV-1001') is missing, so EVERY row is charged.
        int everyRow = SqlLab.Run("UPDATE AccountsScratch SET Balance = Balance - 25;");
        Console.WriteLine($"UPDATE with NO WHERE: {everyRow} rows affected (we meant 1)");
        SqlLab.Show("SELECT AccountId, AccountNumber, Balance FROM AccountsScratch ORDER BY AccountId;");

        // The rows-affected number is your alarm bell: expected 1, got 3. Habits that catch this are in method 6.
        SqlLab.Run("DROP TABLE AccountsScratch;");
    }

    // DELETE removes rows. A foreign key stops you deleting a row that other rows still point to.
    public void ExplainDeleteRows()
    {
        PrintHeading("3. DELETE — removing rows, children before parents");

        // A throwaway customer (Dev Patel) with one account and one deposit, just to delete again.
        // Each (SELECT ...) in a VALUES list looks up the id that the row above was given.
        SqlLab.Run("""
            INSERT INTO Customers (FullName, Email) VALUES (N'Dev Patel', N'dev@example.com');
            INSERT INTO Accounts (CustomerId, AccountNumber, AccountType, Balance)
            VALUES ((SELECT CustomerId FROM Customers WHERE Email = N'dev@example.com'), N'CUR-9001', N'Current', 20);
            INSERT INTO Transactions (AccountId, Amount, Kind)
            VALUES ((SELECT AccountId FROM Accounts WHERE AccountNumber = N'CUR-9001'), 20, N'Deposit');
            """);
        Console.WriteLine("Rows per table before deleting Dev:");
        ShowRowCounts();

        // The chain is Customers <- Accounts <- Transactions: each row points UP at its parent. SQL Server
        // refuses (error 547) to delete a parent while a child still points at it.
        Console.WriteLine("Delete the customer first?");
        SqlLab.ShowError("DELETE FROM Customers WHERE Email = N'dev@example.com';");
        Console.WriteLine("Delete the account first?");
        SqlLab.ShowError("DELETE FROM Accounts WHERE AccountNumber = N'CUR-9001';");

        // The working order is children first: ledger rows, then the account, then the customer.
        // WHERE picks Dev's rows only. Without it, DELETE would try to remove EVERY row in the table.
        int ledgerRows = SqlLab.Run("DELETE FROM Transactions WHERE AccountId = (SELECT AccountId FROM Accounts WHERE AccountNumber = N'CUR-9001');");
        int accountRows = SqlLab.Run("DELETE FROM Accounts WHERE AccountNumber = N'CUR-9001';");
        int customerRows = SqlLab.Run("DELETE FROM Customers WHERE Email = N'dev@example.com';");
        Console.WriteLine($"Deleted children first: {ledgerRows} ledger row, {accountRows} account, {customerRows} customer");
        ShowRowCounts();

        // TRUNCATE TABLE also empties a table, but it takes no WHERE (it is all or nothing), and SQL Server
        // refuses it (error 4712) on a table that a foreign key points to. DELETE keeps the IDENTITY counter
        // going (the next new row continues the numbering); TRUNCATE restarts it from the seed. Rule of thumb: DELETE ... WHERE for rows.
        Console.WriteLine("TRUNCATE the customers table?");
        SqlLab.ShowError("TRUNCATE TABLE Customers;");
    }

    // A transaction groups statements so they all happen, or none do ("all or nothing").
    public void ExplainTransactions()
    {
        PrintHeading("4. Transactions — a transfer that fully happens or not at all");

        // A transfer is four changes: take money from Asha, give it to Ben, and write a ledger row for each.
        // If only some of them stuck, the bank's books would disagree with themselves. Without a transaction
        // every statement is saved on its own the moment it finishes; after BEGIN TRANSACTION nothing is
        // final until COMMIT TRANSACTION makes all of it permanent. This is the A of ACID: Atomicity (the other
        // letters: Consistency, Isolation, Durability).
        Console.WriteLine("Balances before the transfer of 200.00 from Asha to Ben:");
        ShowBalances();

        SqlLab.Run("""
            BEGIN TRANSACTION;
            UPDATE Accounts SET Balance = Balance - 200 WHERE AccountNumber = N'SAV-1001';
            UPDATE Accounts SET Balance = Balance + 200 WHERE AccountNumber = N'CUR-2001';
            INSERT INTO Transactions (AccountId, Amount, Kind)
                SELECT AccountId, 200, N'Withdrawal' FROM Accounts WHERE AccountNumber = N'SAV-1001';
            INSERT INTO Transactions (AccountId, Amount, Kind)
                SELECT AccountId, 200, N'Deposit' FROM Accounts WHERE AccountNumber = N'CUR-2001';
            COMMIT TRANSACTION;
            """);
        Console.WriteLine("After COMMIT — both balances moved, and the ledger has both rows:");
        ShowBalances();
        ShowLedger();

        // Now a transfer the bank must refuse: Asha has 300.00, the request is 900.00. We debit first, LOOK at
        // the result, and ROLLBACK TRANSACTION undoes everything since BEGIN. The @Notes table variable is a
        // notebook that lives for this batch only and, unlike the Accounts table, a ROLLBACK does not undo
        // what we write in it — so we can show what Asha's balance was INSIDE the transaction.
        Console.WriteLine("A transfer of 900.00 from Asha — the balance goes negative, so we ROLLBACK:");
        SqlLab.Show("""
            DECLARE @Notes TABLE (Moment NVARCHAR(40), AshaBalance DECIMAL(18,2));
            BEGIN TRANSACTION;
            UPDATE Accounts SET Balance = Balance - 900 WHERE AccountNumber = N'SAV-1001';
            INSERT INTO @Notes SELECT N'inside, after the debit', Balance FROM Accounts WHERE AccountNumber = N'SAV-1001';
            IF (SELECT Balance FROM Accounts WHERE AccountNumber = N'SAV-1001') < 0
                ROLLBACK TRANSACTION;
            ELSE
                COMMIT TRANSACTION;
            INSERT INTO @Notes SELECT N'after the ROLLBACK', Balance FROM Accounts WHERE AccountNumber = N'SAV-1001';
            SELECT Moment, AshaBalance FROM @Notes;
            """);
    }

    // When a statement fails inside a transaction, what happens to the rest? SET XACT_ABORT decides.
    public void ExplainXactAbort()
    {
        PrintHeading("5. SET XACT_ABORT ON — one failure undoes the whole transfer");

        // The same transfer of 50.00 both times; the third step has a typo (account 99 does not exist),
        // so the foreign key rejects it with error 547 (a typing mistake in the SQL text itself would be a
        // compile error, a different case).
        // Note: SqlLab.ShowError prints "SQL Server refused it" even when the batch carries on after the error (see OFF below).
        string transfer = """
            BEGIN TRANSACTION;
            UPDATE Accounts SET Balance = Balance - 50 WHERE AccountNumber = N'SAV-1001';
            INSERT INTO Transactions (AccountId, Amount, Kind)
                SELECT AccountId, 50, N'Withdrawal' FROM Accounts WHERE AccountNumber = N'SAV-1001';
            INSERT INTO Transactions (AccountId, Amount, Kind) VALUES (99, 50, N'Deposit');
            UPDATE Accounts SET Balance = Balance + 50 WHERE AccountNumber = N'CUR-2001';
            COMMIT TRANSACTION;
            """;

        // XACT_ABORT OFF (the usual starting setting): a constraint error only cancels THAT statement. The
        // batch carries on, reaches COMMIT, and saves everything that did work — a half-done transfer.
        Console.WriteLine("XACT_ABORT OFF: the typo statement fails, the rest carries on and commits:");
        SqlLab.ShowError("SET XACT_ABORT OFF;\n" + transfer);
        ShowBalances();
        ShowLedger();

        // Clean-up by hand (the missing deposit row) — exactly the chore a transaction should have saved us.
        int repaired = SqlLab.Run("""
            INSERT INTO Transactions (AccountId, Amount, Kind)
                SELECT AccountId, 50, N'Deposit' FROM Accounts WHERE AccountNumber = N'CUR-2001';
            """);
        Console.WriteLine($"Repaired by hand: {repaired} ledger row added. Balances are now 250.00 / 250.00.");

        // XACT_ABORT ON: any run-time error rolls back the whole open transaction and stops the batch,
        // so COMMIT is never reached. We run the same text again: error 547 again, nothing changes.
        Console.WriteLine("XACT_ABORT ON: the same typo undoes the whole transfer:");
        SqlLab.ShowError("SET XACT_ABORT ON;\n" + transfer);
        ShowBalances();
    }

    // Two habits that catch the mistakes from methods 2 and 3 before they do damage.
    public void ExplainSafeHabits()
    {
        PrintHeading("6. Safe habits — look first, then change, then check the count");

        // Habit 1: run the WHERE as a SELECT first. Those are exactly the rows an UPDATE or DELETE with
        // the same WHERE would touch. Here: a 10.00 welcome bonus for every Savings account.
        Console.WriteLine("Preview: which rows does WHERE AccountType = 'Savings' hit?");
        SqlLab.Show("SELECT AccountNumber, Balance FROM Accounts WHERE AccountType = N'Savings' ORDER BY AccountId;");

        // Habit 2: wrap the change in a transaction and compare the row count with what you expect
        // (2, from the preview). The IF @@ROWCOUNT check must come straight after the UPDATE.
        // Right WHERE: 2 rows, so COMMIT.
        Console.WriteLine("The bonus with its WHERE:");
        SqlLab.Show("""
            BEGIN TRANSACTION;
            UPDATE Accounts SET Balance = Balance + 10 WHERE AccountType = N'Savings';
            IF @@ROWCOUNT = 2
            BEGIN
                COMMIT TRANSACTION;
                SELECT N'committed: 2 rows, as expected' AS Outcome;
            END
            ELSE
            BEGIN
                ROLLBACK TRANSACTION;
                SELECT N'rolled back: expected 2 rows' AS Outcome;
            END
            """);
        ShowBalances();

        // The same guard, but the WHERE is forgotten: 3 rows change inside the transaction, the count is
        // wrong, ROLLBACK puts every balance back.
        Console.WriteLine("The same bonus with the WHERE forgotten:");
        SqlLab.Show("""
            BEGIN TRANSACTION;
            UPDATE Accounts SET Balance = Balance + 10;
            IF @@ROWCOUNT = 2
            BEGIN
                COMMIT TRANSACTION;
                SELECT N'committed: 2 rows, as expected' AS Outcome;
            END
            ELSE
            BEGIN
                ROLLBACK TRANSACTION;
                SELECT N'rolled back: expected 2 rows' AS Outcome;
            END
            """);
        ShowBalances();
    }

    // How many rows each bank table holds — one grid instead of three SELECTs.
    private static void ShowRowCounts()
    {
        SqlLab.Show("""
            SELECT N'Customers' AS TableName, COUNT(*) AS TotalRows FROM Customers
            UNION ALL SELECT N'Accounts', COUNT(*) FROM Accounts
            UNION ALL SELECT N'Transactions', COUNT(*) FROM Transactions;
            """);
    }

    // Every account and its balance, in a fixed order.
    private static void ShowBalances()
    {
        SqlLab.Show("SELECT AccountNumber, Balance FROM Accounts ORDER BY AccountId;");
    }

    // The ledger, one row per movement. JOIN looks up each row's account number from the Accounts table.
    private static void ShowLedger()
    {
        SqlLab.Show("""
            SELECT a.AccountNumber, t.Kind, t.Amount
            FROM Transactions AS t JOIN Accounts AS a ON a.AccountId = t.AccountId
            ORDER BY t.TransactionId;
            """);
    }

    private static void PrintHeading(string title)
    {
        Console.WriteLine();
        Console.WriteLine(new string('=', title.Length));
        Console.WriteLine(title);
        Console.WriteLine(new string('=', title.Length));
    }
}
